int __io_putchar(int ch)
{
    uint8_t c = (uint8_t)ch;
    if (ch == '\n')              /* nette CRLF voor de terminal */
    {
        uint8_t r = '\r';
        HAL_UART_Transmit(&huart1, &r, 1, 100);
    }
    HAL_UART_Transmit(&huart1, &c, 1, 100);
    return ch;
}


